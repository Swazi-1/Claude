"""S10: checkable predictions for the owner's rides (no motor constant fitted).

Code facts used (see report): battery-current ceiling in Sport (RC02) = 560
counts; 27.5 counts per amp (firmware's own x1000/275 conversion, matched by
the owner's 20.35 A plateau); q-axis is a voltage command limited to a
fixed fraction of the battery voltage, d-current held at 0 (no field
weakening) -> the speed at which current must start to fall scales with the
loaded battery voltage. Coast-regen gate: battery voltage reading < 54.0 V.

Measured input (owner, 2026-10-03): 54.15 V at rest, 51.14 V at 20.35 A.
The internal-resistance estimate comes from that sag, not from the speed.
The only absolute speed anchor is the owner's recalled onset (20-22 km/h)
at 54.15 V; everything else is a ratio and does not depend on the anchor.

Output: evidence/s10_predictions.md
"""
import os

EV = os.path.join(os.path.dirname(__file__), "..", "evidence")

I_CEIL = 560 / 27.5                  # A, RC02 Sport ceiling
R_BATT = (54.15 - 51.14) / 20.35     # ohm, from owner's sag
V_REF_LOADED = 54.15 - I_CEIL * R_BATT
ANCHOR = (20.0, 22.0)                # km/h, recalled onset at 54.15 V (not a measurement)
GATE = 54.0                          # V, coast-regen gate (0.1 V scale is strong evidence)


def main():
    out = ["# Ride predictions (generated by scripts/s10_predictions.py)", "",
           f"Battery-current ceiling (RC02 Sport): {I_CEIL:.2f} A. Battery resistance from owner's sag: {R_BATT:.3f} ohm.",
           f"Loaded voltage at the ceiling in the 100 % run: {V_REF_LOADED:.2f} V.", "",
           "## A. Where power starts to fall (voltage-headroom hypothesis)", "",
           "| rest voltage | loaded V at 20.4 A | onset ratio vs 54.15 V run | onset if anchor 20-22 km/h | peak electrical power |",
           "|---|---|---|---|---|"]
    for v in (54.0, 50.0, 48.0, 46.0):
        vl = v - I_CEIL * R_BATT
        r = vl / V_REF_LOADED
        out.append(f"| {v:.0f} V | {vl:.1f} V | {r:.3f} | {ANCHOR[0]*r:.1f}-{ANCHOR[1]*r:.1f} km/h | {vl*I_CEIL:.0f} W |")
    out += ["",
            "Notes: the ratio column is the real test (it does not use the anchor). Resistance rises at low charge and in the cold,",
            "which pushes the low-voltage onsets slightly lower still. A speed-linked limiter instead predicts the same onset at every voltage.", "",
            "## B. Coast regen near full charge (54.0 V gate)", "",
            "Regen raises the terminal voltage by I x R, so near the gate the controller lets regen grow only until the reading reaches about 54.0 V.",
            "", "| open-circuit voltage | max coast-regen current before the reading hits 54.0 V |", "|---|---|"]
    for ocv in (54.15, 54.0, 53.8, 53.6, 53.4, 53.0, 52.0, 50.0):
        i = max(0.0, (GATE - ocv) / R_BATT)
        txt = f"{i:.1f} A" if i < 25 else "not limited by the gate (other limits apply)"
        out.append(f"| {ocv:.2f} V | {txt} |")
    out += ["", "Calibration warning: the controller's voltage reading and the app's voltage (from the battery) are different sensors;",
            "an offset of a few tenths of a volt between them is possible and unmeasured."]
    open(os.path.join(EV, "s10_predictions.md"), "w").write("\n".join(out) + "\n")
    print("\n".join(out))


if __name__ == "__main__":
    main()
